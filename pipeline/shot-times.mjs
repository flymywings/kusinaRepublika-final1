// Resolve a shot list (film-shots.json) against a words file and print the shot table with frames.
// usage: node pipeline/shot-times.mjs <film-shots.json> [--write <out.md>]
// A shot starts on a word: {"at":{"line":5,"word":"mountain","nth":1}} (nth match in that line, default 1; case and punctuation ignored) or on the end of a line:
// {"at":{"line":11,"edge":"end"}}. A shot ends where the next one starts; the last ends at the end of the audio. Nothing here retimes the voice.
import fs from 'node:fs';
import path from 'node:path';
import {resolveShots} from './film-time.mjs';
const [,,file,flag,outFile]=process.argv;
if(!file){console.error('usage: shot-times.mjs film-shots.json [--write out.md]');process.exit(2);}
const J=JSON.parse(fs.readFileSync(file,'utf8')),dir=path.dirname(path.resolve(file));
const WJ=JSON.parse(fs.readFileSync(path.resolve(dir,J.words),'utf8')),FPS=J.fps??30,norm=s=>s.toLowerCase().replace(/[^a-z0-9']/g,'');
const frameOf=t=>Math.round(t*FPS);
const shots=resolveShots(J,WJ);
const endT=WJ.duration;
const bad=[];shots.forEach((s,i)=>{if(i&&s.f0<=shots[i-1].f0)bad.push(s.id+' does not start after '+shots[i-1].id);});
if(bad.length)throw Error(bad.join('; '));
const LO=1.5-4/FPS,HI=2.0+4/FPS; // the user's rule: 1.5-2 s within 4 frames
const flag_=s=>s.exception?'':s.sec>HI?'LONG':s.sec<LO?'SHORT':'';
const rows=shots.map(s=>`| ${s.id} | f${s.f0}-${s.f1-1} | ${s.sec.toFixed(2)} s${flag_(s)?' '+flag_(s):''} | ${s.at.edge?'end of line '+s.at.line:'"'+s.at.word+'"'} | ${s.subject} | ${s.camera} | ${s.light} | ${s.sound} | ${s.captions??''} | ${s.risk??''} |`);
const sum={count:shots.length,frames:frameOf(endT)-shots[0].f0,long:shots.filter(s=>flag_(s)==='LONG').map(s=>s.id),short:shots.filter(s=>flag_(s)==='SHORT').map(s=>s.id),risk:shots.filter(s=>s.risk).map(s=>s.id+' ('+s.risk+')')};
const b=J.build,order=b?[['Proof first',b.proof],['Chunk A',b.chunkA],['Chunk B',b.chunkB]].map(([n,ids])=>`- ${n}: ${ids.join(', ')} (${ids.reduce((s,i)=>s+shots.find(x=>x.id===i).sec,0).toFixed(1)} s)`).join('\n'):'';
const md=`# Film shot list, cards 2-7 (generated by pipeline/shot-times.mjs from film-shots.json and ${J.words})

${J.rules}

Audio ${WJ.duration} s = ${frameOf(WJ.duration)} frames at ${FPS} fps. The hook is f0-f${J.hookEndsOnFrame-1}; these shots run from f${shots[0].f0}. ${sum.count} shots.
Build order:
${order}

| Shot | Frames | Length | Starts on | Subject | Camera | Light | Sound | Captions | Risk |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Length flags (outside 1.5-2.0 s, 4 frames tolerance; shots with an exception field are skipped): ${[...sum.long.map(i=>i+' long'),...sum.short.map(i=>i+' short')].join(', ')||'none'}.
Risky shots (need new motion or a prop interaction): ${sum.risk.join('; ')||'none'}.
`;
if(flag==='--write'){if(fs.existsSync(outFile))throw Error('refusing to overwrite '+outFile);fs.writeFileSync(outFile,md);console.log('wrote',outFile);}
console.log(shots.map(s=>`${s.id.padEnd(3)} f${String(s.f0).padStart(4)}-${String(s.f1-1).padStart(4)} ${s.sec.toFixed(2)}s ${flag_(s)}`).join('\n'));
console.log(JSON.stringify(sum));
